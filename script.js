/* ================= SHOW PRODUK ================= */

function showProduk(kategori){

  const produkGrid =
    document.getElementById("produkGrid");

  const judulProduk =
    document.getElementById("judulProduk");

  produkGrid.innerHTML = "";

  judulProduk.innerHTML =
    kategori.charAt(0).toUpperCase() +
    kategori.slice(1);

  produkData[kategori].forEach((item)=>{

    produkGrid.innerHTML += `

      <div
        class="produk-card"
        onclick='showDetail(${JSON.stringify(item)})'
      >

        <img src="${item.gambar}" />

        <h3>${item.nama}</h3>

      </div>

    `;

  });

  document
    .getElementById("produkSection")
    .scrollIntoView({
      behavior:"smooth"
    });

}

/* ================= DETAIL ================= */

function showDetail(item){

  const detailBox =
    document.getElementById("detailBox");

  detailBox.innerHTML = `

    <div class="detail-content">

      <button
        class="close-btn"
        onclick="closeDetail()"
      >
        ×
      </button>

      <div class="detail-left">

        <img src="${item.gambar}" />

      </div>

      <div class="detail-right">

        <h2>${item.nama}</h2>

        <p class="detail-deskripsi">

          ${item.deskripsi}

        </p>

        <button
          class="spec-btn"
          onclick='showSpec(${JSON.stringify(item.spesifikasi)})'
        >
          Lihat Spesifikasi
        </button>

      </div>

    </div>

  `;

  detailBox.style.display = "flex";

}

/* ================= SPEC ================= */

function showSpec(specs){

  const detailBox =
    document.getElementById("detailBox");

  detailBox.innerHTML = `

    <div class="spec-popup">

      <button
        class="close-btn"
        onclick="closeDetail()"
      >
        ×
      </button>

      <h2>Spesifikasi Produk</h2>

      <table class="spec-table">

        ${specs.map(spec => `

          <tr>

            <td>${spec}</td>

          </tr>

        `).join("")}

      </table>

    </div>

  `;

}

/* ================= CLOSE ================= */

function closeDetail(){

  const detailBox =
    document.getElementById("detailBox");

  detailBox.style.display = "none";

  detailBox.innerHTML = "";

}